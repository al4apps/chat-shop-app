package com.al4apps.chatshop.core.session

/** Защищённое хранилище токенов сессии. */
interface TokenStorage {

    /**
     * Синхронно читает сохранённую пару токенов.
     * Используется на старте приложения для мгновенного выбора стартового экрана.
     *
     * @return пара токенов или null, если пользователь не авторизован.
     */
    fun readInitial(): AuthTokens?

    /**
     * Читает актуальную пару токенов.
     *
     * @return пара токенов или null, если пользователь не авторизован.
     */
    suspend fun read(): AuthTokens?

    /**
     * Атомарно сохраняет новую пару токенов (перезаписывает старую целиком).
     * Дожидается фиксации на диске — после возврата пара гарантированно сохранена.
     */
    suspend fun save(tokens: AuthTokens)

    /** Удаляет сохранённую пару токенов (выход/умершая сессия). */
    suspend fun clear()
}
